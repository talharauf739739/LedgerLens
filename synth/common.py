def q(x: Decimal | int | float | str) -> Decimal:
    return Decimal(str(x)).quantize(CENT, rounding=ROUND_HALF_UP)


# --- fonts ---------------------------------------------------------------------------------

FONT_FAMILIES = {
    "helvetica": ("Helvetica", "Helvetica-Bold"),
    "times": ("Times-Roman", "Times-Bold"),
    "courier": ("Courier", "Courier-Bold"),
}


@dataclass(frozen=True)
class Fonts:
    regular: str
    bold: str

    @classmethod
    def pick(cls, rng: random.Random) -> Fonts:
        reg, bold = FONT_FAMILIES[rng.choice(sorted(FONT_FAMILIES))]
        return cls(reg, bold)


# --- bbox-recording writer -----------------------------------------------------------------


class PdfWriter:
    """Thin ReportLab wrapper. Coordinates are top-left origin (y grows downward) to match
    `Source.bbox`; `y` is the text baseline."""

    def __init__(self, pagesize: tuple[float, float]) -> None:
        self.buf = io.BytesIO()
        self.width, self.height = pagesize
        self.c = Canvas(self.buf, pagesize=pagesize, invariant=True)
        self.c.setTitle("LedgerLens synthetic sample")
        self.c.setAuthor("LedgerLens synth")
        self.page = 1

    def text(
        self,
        x: float,
        y: float,
        s: str,
        font: str,
        size: float,
        align: Literal["left", "right", "center"] = "left",
    ) -> Source:
        w = stringWidth(s, font, size)
        x0 = {"left": x, "right": x - w, "center": x - w / 2}[align]
        self.c.setFont(font, size)
        self.c.drawString(x0, self.height - y, s)
        ascent, descent = getAscentDescent(font, size)
        return Source(
            page=self.page,
            bbox=(round(x0, 2), round(y - ascent, 2), round(x0 + w, 2), round(y - descent, 2)),
        )

    def runs(self, x: float, y: float, parts: list[tuple[str, str]], size: float) -> list[Source]:
        """Draw consecutive (text, font) runs on one line; return each run's box."""
        boxes = []
        for s, font in parts:
            box = self.text(x, y, s, font, size)
            boxes.append(box)
            x = box.bbox[2]
        return boxes

    def hline(self, x0: float, x1: float, y: float, width: float = 0.5) -> None:
        self.c.setLineWidth(width)
        self.c.line(x0, self.height - y, x1, self.height - y)

    def rect(self, x0: float, y0: float, x1: float, y1: float, gray: float = 0.92) -> None:
        self.c.setFillGray(gray)
        self.c.rect(x0, self.height - y1, x1 - x0, y1 - y0, stroke=0, fill=1)
        self.c.setFillGray(0)

    def footer(self, font: str) -> None:
        self.text(self.width / 2, self.height - 24, FOOTER, font, 6.5, align="center")
        self.text(self.width - 40, self.height - 24, f"Page {self.page}", font, 7, align="right")

    def new_page(self) -> None:
        self.c.showPage()
        self.page += 1

    def fit(self, s: str, font: str, size: float, max_w: float) -> str:
        if stringWidth(s, font, size) <= max_w:
            return s
        while s and stringWidth(s + "...", font, size) > max_w:
            s = s[:-1]
        return s.rstrip() + "..."

    def save(self) -> bytes:
        self.c.save()
        return self.buf.getvalue()


def page_size(country: str) -> tuple[float, float]:
    size: tuple[float, float] = letter if country == "US" else A4
    return size


# --- money and dates ---------------------------------------------------------------------

MoneyStyle = Literal["us", "eu"]
CURRENCY_SYMBOL = {"USD": "$", "GBP": "£", "EUR": "€"}


def fmt_money(
    amount: Decimal,
    style: MoneyStyle,
    symbol: str = "",
    negative: Literal["minus", "parens"] = "minus",
) -> str:
    neg = amount < 0
    whole, frac = f"{abs(amount):.2f}".split(".")
    groups = f"{int(whole):,}"
    body = f"{groups}.{frac}" if style == "us" else f"{groups.replace(',', '.')},{frac}"
    if symbol:
        body = f"{symbol}{body}" if style == "us" else f"{body} {symbol}"
    if neg:
        return f"({body})" if negative == "parens" else f"-{body}"
    return body


DATE_FORMATS = {"us": "%m/%d/%Y", "uk": "%d %b %Y", "de": "%d.%m.%Y", "iso": "%Y-%m-%d"}


def fmt_date(d: date, style: str) -> str:
    return d.strftime(DATE_FORMATS[style])


