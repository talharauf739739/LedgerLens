def bank_name(rng: random.Random) -> str:
    return f"{rng.choice(_BANK_WORDS_A)} {rng.choice(_BANK_WORDS_B)}"


def digits(rng: random.Random, n: int) -> str:
    return "".join(rng.choice(string.digits) for _ in range(n))


def _iban_check_digits(country: str, bban: str) -> str:
    rearranged = bban + country + "00"
    num = int("".join(str(int(ch, 36)) for ch in rearranged))
    return f"{98 - num % 97:02d}"


def fake_iban(rng: random.Random, country: str) -> str:
    """A checksum-valid IBAN with random (fictitious) bank and account parts."""
    if country == "GB":
        bban = "LLNS" + digits(rng, 6) + digits(rng, 8)
    elif country == "DE":
        bban = digits(rng, 18)
    elif country == "NL":
        bban = "LLNS" + digits(rng, 10)
    elif country == "FR":
        bban = (
            digits(rng, 10)
            + "".join(rng.choice(string.ascii_uppercase) for _ in range(2))
            + digits(rng, 11)
        )
    else:
        raise ValueError(f"no IBAN format for {country}")
    return country + _iban_check_digits(country, bban) + bban


def group4(s: str) -> str:
    return " ".join(s[i : i + 4] for i in range(0, len(s), 4))


# --- truth file -----------------------------------------------------------------------------


class Tampering(BaseModel):
    row: int
    field: str
    original: str
    printed: str


class SyntheticMeta(BaseModel):
    id: str
    doc_type: str
    variant: Variant
    seed: int
    template: str
    generator_version: str = GENERATOR_VERSION
    # Exactly what was printed for each field (before masking), for grounding tests/eval.
    printed: dict[str, str] = PydanticField(default_factory=dict)
    tampering: Tampering | None = None
    expected_failures: list[str] = []
    noise: dict[str, Any] | None = None


@dataclass
class Generated:
    pdf: bytes
    document: Any  # a BaseDocument subclass instance
    meta: SyntheticMeta

    def truth_json(self) -> dict[str, Any]:
        return {
            "synthetic": self.meta.model_dump(mode="json"),
            "document": self.document.model_dump_doc(),
        }
